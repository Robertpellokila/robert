const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { test } = require('node:test')
const root = path.resolve(__dirname, '..')
const read = file => fs.readFileSync(path.join(root,file),'utf8')
const page = read('pages/index.vue')
const lite = read('components/LitePortfolio.vue')
const interiors = read('world/createInteriors.ts')
const decor = read('world/roomDecor.ts')
const world = read('world/createWorld.ts')
const styles = read('assets/css/lite-premium.css')
const splashStyles = read('assets/css/welcome-premium.css')

test('initial welcome has intro and choice states with a real 3D preview',()=>{
  const entry=read('components/PortfolioEntryOverlay.vue')
  assert.match(page,/showWelcomeSplash = computed\(\(\) => !welcomeCompleted\.value\)/)
  assert.match(page,/entryStage = ref<EntryStage>\('intro'\)/)
  assert.match(page,/startIntro\(\)/)
  assert.match(page,/:inert="showWelcomeSplash"/)
  assert.match(page,/:three-d-background="experienceMode === '3d' && !worldLoading"/)
  assert.match(entry,/@click="emit\('choose','lite'\)"/)
  assert.match(entry,/@click="emit\('choose','3d'\)"/)
})
test('splash has animated CSS and a reduced motion fallback',()=>{
  assert.match(splashStyles,/@keyframes v087-float/)
  assert.match(splashStyles,/@media\(prefers-reduced-motion:reduce\)/)
  assert.match(splashStyles,/@media\(max-width:790px\)/)
})
test('lite mode is an actual complete professional portfolio with filters',()=>{
  for(const section of ['home','about','experience','skills','projects','contact']) assert.ok(lite.includes(`id="lite-${section}"`))
  assert.match(lite,/projectFilter = ref\('All'\)/)
  assert.match(lite,/displayedProjects = computed/)
  assert.match(lite,/<GitHubHighlights\s*\/>/)
  assert.match(lite,/to="\/resume"/)
  assert.match(lite,/emit\('switch3d'\)/)
})
test('lite portfolio has mobile navigation and reduced motion',()=>{
  assert.match(lite,/:aria-expanded="menuOpen"/)
  assert.match(styles,/@media\(max-width:780px\)/)
  assert.match(styles,/@media\(prefers-reduced-motion:reduce\)/)
})
test('every room has its own decor builder and furniture refinements',()=>{
  for(const room of ['home','about','experience','skills','projects','contact']) assert.match(decor,new RegExp(`function ${room}\\(p:Parent\\)`))
  assert.match(decor,/function keyboard/)
  assert.match(decor,/function seatedWorker/)
  assert.match(decor,/monitor\(p,\.68,-1\.22,[^\n]*'laptop'/)
  assert.match(decor,/careerBoard\.userData\.interactiveObjectId='career'/)
})
test('seated workers face -Z, toward the back-wall monitor',()=>{
  assert.match(decor,/seatedWorker\(p,\.68,-\.37,'#5F8B6E','#1D2024',0\)/)
  assert.match(decor,/seatedWorker\(p,\.18,-\.25,'#C7869F','#4A3A33',0\)/)
})
test('bubbles are camera-facing and sphere hints are not displayed',()=>{
  assert.match(interiors,/function clickBubble/)
  assert.match(interiors,/Click me/)
  assert.match(interiors,/new THREE\.PlaneGeometry\(width,height\)/)
  assert.doesNotMatch(interiors,/new THREE\.IcosahedronGeometry\(\.14,1\)/)
  assert.match(world,/hit\.quaternion\.copy\(firstPersonCamera\.quaternion\)/)
})
test('important furniture objects can also be clicked',()=>{
  assert.match(interiors,/interactiveObjectId/)
  assert.match(decor,/interactiveObjectId='email'/)
  assert.match(decor,/interactiveObjectId='career'/)
})
