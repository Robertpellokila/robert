const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const page=read('pages/index.vue')
const entry=read('components/PortfolioEntryOverlay.vue')
const css=read('assets/css/entry-cinematic.css')
const config=read('data/portfolio.ts')
const nuxt=read('nuxt.config.ts')
let passed=0
function test(name, fn){fn();passed++;console.log('✔',name)}
test('intro and chooser are two distinct stages',()=>{
 assert.match(page,/type EntryStage = 'intro' \| 'choose' \| 'done'/)
 assert.match(page,/introTimeout = setTimeout\(finishIntro, reducedMotion \? 350 : welcomeSettings\.introDurationMs\)/)
 assert.match(entry,/v-if="stage === 'intro'"/)
 assert.match(entry,/v-if="stage === 'choose'"/)
})
test('intro offers skip and zoom animation',()=>{
 assert.match(entry,/@click="emit\('skip'\)"/)
 assert.match(css,/@keyframes mlw-intro-zoom/)
 assert.match(css,/@keyframes mlw-intro-load/)
 assert.match(css,/@media\(prefers-reduced-motion:reduce\)/)
})
test('choice modal is compact and real scene remains visible behind it',()=>{
 assert.match(page,/:three-d-background="experienceMode === '3d' && !worldLoading"/)
 assert.match(page,/experienceMode.value = welcomeCompleted.value/)
 assert.match(page,/webglAvailable.value && !reducedMotion \? '3d' : 'lite'/)
 assert.match(css,/\.mlw-choice-card \{[^}]*width:min\(410px,100%\)/)
 assert.match(css,/\.is-welcome-preview \.site-shell > :not\(\.scene-layer\)/)
})
test('selection and Lite Explore 3D use direct changeExperience',()=>{
 assert.match(page,/function beginExperience\(mode: ExperienceMode\)[\s\S]*?changeExperience\(mode\)/)
 assert.match(page,/function goDirectlyTo3D\(\)[\s\S]*?changeExperience\('3d'\)/)
 assert.match(entry,/@click="emit\('choose','lite'\)"/)
 assert.match(entry,/@click="emit\('choose','3d'\)"/)
})
test('photo is optional; safely defaults to configured portrait',()=>{
 assert.match(config,/introPhoto: ''/)
 assert.match(page,/:photo="owner.introPhoto \|\| owner.photo"/)
 assert.match(entry,/@error="photoFailed = true"/)
})
test('startup overlay is responsive with non-WebGL fallback',()=>{
 assert.match(css,/@media\(max-width:760px\)/)
 assert.match(entry,/v-if="!threeDBackground"/)
 assert.match(entry,/:disabled="!webglAvailable"/)
 assert.match(nuxt,/entry-cinematic.css/)
})
console.log(`${passed} v0.8.9 entry checks passed (source-level only).`)
